"""Write docs/GUIDE.md, the feature guide as one readable page, from the same files the in-app Guide window uses (V-037):
app/config/guide.json (chapters -> topics), strings/ui.json (every sentence), hotkeys.json + panels/*.json (key caps and window
names) and strings/tooltips.json (setting names). Edit those files, never GUIDE.md, then run this again.

Usage: python scripts/make_guide.py [--check]
  --check   only say whether docs/GUIDE.md is up to date (exit 1 if not)"""
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONFIG = os.path.join(ROOT, "app", "config")
OUT = os.path.join(ROOT, "docs", "GUIDE.md")
KEY_NAME = {"enter": "Enter", "escape": "Esc"}
ACTION_WORDS = {"verify": "action.verify", "pause": "action.pause", "jukebox": "jukebox.key", "jukebox_next": "jukebox.key_next", "chat": "chat.key", "esc_menu": "esc.title"}


def _load(*parts):
    with open(os.path.join(CONFIG, *parts), encoding="utf-8") as f:
        return json.load(f)


def load():
    panels = {}
    for name in sorted(os.listdir(os.path.join(CONFIG, "panels"))):
        if name.endswith(".json"):
            panels[name[:-5]] = _load("panels", name)
    return {"guide": _load("guide.json"), "ui": _load("strings", "ui.json"), "tips": _load("strings", "tooltips.json"),
            "hotkeys": _load("hotkeys.json"), "panels": panels}


def key_label(cfg, name):
    """Same rule as keyLabel() in app/web/js/panels/help.js: the window's title, else the action's wording, else the name made readable."""
    ui = cfg["ui"]
    for p in cfg["panels"].values():
        if p.get("hotkey") == name and p.get("title"):
            return ui.get(p["title"], p["title"])
    w = ACTION_WORDS.get(name)
    if w and w in ui:
        return ui[w]
    plain = name.replace("_", " ")
    return plain[:1].upper() + plain[1:]


def key_cap(key):
    return KEY_NAME.get(key, key.upper())


def window_name(cfg, name):
    p = cfg["panels"].get(name, {})
    return cfg["ui"].get(p.get("title") or "a11y." + name, name)


def render(cfg):
    ui, chapters = cfg["ui"], cfg["guide"]["chapters"]
    out = ["# %s" % ui["guide.title"], "",
           "Every feature of Vanilla Agents and how to use it. In the window: Help (F1) > %s, Esc > %s, or the %s button in Options." % (
               ui["guide.ui_button"], ui["guide.ui_menu"], ui["guide.ui_q"]), "",
           "<!-- Made by scripts/make_guide.py from app/config/guide.json and strings/ui.json. Do not edit this file; edit those and run the script. -->", "",
           "## Contents", ""]
    for ch in chapters:
        out.append("- [%s](#%s)" % (ui[ch["title"]], "chapter-" + ch["id"]))
    for ch in chapters:
        out += ["", '<a id="chapter-%s"></a>' % ch["id"], "", "## %s" % ui[ch["title"]]]
        for tp in ch["topics"]:
            out += ["", "### %s" % ui[tp["title"]]]
            for k in tp["body"]:
                out += ["", ui[k]]
            keys = [k for k in tp.get("keys", []) if k in cfg["hotkeys"]]
            if keys:
                out += ["", "%s: %s" % (ui["guide.ui_keys"], ", ".join("`%s` %s" % (key_cap(cfg["hotkeys"][k]), key_label(cfg, k)) for k in keys))]
            extra = []
            if tp.get("panel"):
                extra.append("%s: %s" % (ui["guide.ui_open"], window_name(cfg, tp["panel"])))
            if tp.get("setting"):
                t = cfg["tips"].get("setting_" + tp["setting"], {})
                extra.append("%s: %s" % (ui["guide.ui_setting"], t.get("title", tp["setting"])))
            if extra:
                out += ["", "*%s*" % " · ".join(extra)]
    return "\n".join(out).rstrip() + "\n"


def main(argv=None):
    a = argparse.ArgumentParser(description="Write docs/GUIDE.md from the guide config.")
    a.add_argument("--check", action="store_true", help="only check that docs/GUIDE.md is up to date")
    args = a.parse_args(argv)
    text = render(load())
    try:
        with open(OUT, encoding="utf-8") as f:
            old = f.read()
    except OSError:
        old = None
    if args.check:
        if old != text:
            print("docs/GUIDE.md is out of date: run python scripts/make_guide.py")
            return 1
        print("docs/GUIDE.md is up to date.")
        return 0
    if old != text:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote docs/GUIDE.md")
    else:
        print("docs/GUIDE.md was already up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
